package org.springframework.samples.petclinic.util;

/**
 * Utility for computing the Luhn check digit over a string.
 */
public final class Luhn {

    private Luhn() {
    }

    /**
     * Compute the Luhn check digit (0-9) over the decimal digits contained in {@code value},
     * ignoring any non-digit characters.
     *
     * @param value the string whose digits form the payload
     * @return the single check digit that makes the payload plus digit a valid Luhn sequence
     */
    public static int checkDigit(String value) {
        int sum = 0;
        boolean doubleDigit = true;
        for (int i = value.length() - 1; i >= 0; i--) {
            char c = value.charAt(i);
            if (c < '0' || c > '9') {
                continue;
            }
            int digit = c - '0';
            if (doubleDigit) {
                digit *= 2;
                if (digit > 9) {
                    digit -= 9;
                }
            }
            sum += digit;
            doubleDigit = !doubleDigit;
        }
        return (10 - (sum % 10)) % 10;
    }
}
