package org.springframework.samples.petclinic.rest.function.owner;

import net.officefloor.plugin.variable.Val;
import org.springframework.samples.petclinic.model.Owner;
import org.springframework.samples.petclinic.repository.OwnerRepository;

/**
 * Soft-deletes the owner: flags it {@code deleted} true and saves, retaining the row. The record is
 * still returned by {@code GET /api/owners/{id}} (with {@code deleted} true), and the create
 * endpoint's duplicate and identity checks then ignore it.
 */
public class DeleteOwner {

    public void service(@Val Owner owner, OwnerRepository ownerRepository) {
        owner.setDeleted(true);
        ownerRepository.save(owner);
    }
}
