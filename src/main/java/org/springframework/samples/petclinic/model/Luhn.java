package org.springframework.samples.petclinic.model;

/**
 * Luhn check-digit algorithm. Non-digit characters are ignored, so the check digit is computed
 * over the digits contained in the input in their original order.
 */
public final class Luhn {

    private Luhn() {
    }

    /**
     * Compute the Luhn check digit (0-9) over the digits contained in the given value. Starting
     * from the right-most digit every second digit is doubled (subtracting 9 when the result
     * exceeds nine); the check digit is the amount needed to bring the running total to a
     * multiple of ten.
     */
    public static int checkDigit(String value) {
        int sum = 0;
        boolean doubleDigit = true;
        for (int i = value.length() - 1; i >= 0; i--) {
            char c = value.charAt(i);
            if (c < '0' || c > '9') {
                continue;
            }
            int d = c - '0';
            if (doubleDigit) {
                d *= 2;
                if (d > 9) {
                    d -= 9;
                }
            }
            sum += d;
            doubleDigit = !doubleDigit;
        }
        return (10 - (sum % 10)) % 10;
    }
}
